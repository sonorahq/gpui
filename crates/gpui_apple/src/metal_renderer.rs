    pub fn draw(&mut self, scene: &Scene) {
        let layer = match &self.layer {
            Some(l) => l.clone(),
            None => {
                log::error!(
                    "draw() called on headless renderer - use render_scene_to_image() instead"
                );
                return;
            }
        };
        let viewport_size = layer.drawable_size();
        let viewport_size: Size<DevicePixels> = size(
            (viewport_size.width.ceil() as i32).into(),
            (viewport_size.height.ceil() as i32).into(),
        );
        let drawable = if let Some(drawable) = layer.next_drawable() {
            drawable
        } else {
            log::error!(
                "failed to retrieve next drawable, drawable size: {:?}",
                viewport_size
            );
            return;
        };

        let command_buffer = match self.render_frame(scene, drawable.texture(), viewport_size) {
            Ok(command_buffer) => command_buffer,
            Err(error) => {
                log::error!("failed to render: {error:#}");
                return;
            }
        };

        if self.presents_with_transaction {
            command_buffer.commit();
            command_buffer.wait_until_scheduled();
            drawable.present();
        } else {
            command_buffer.present_drawable(drawable);
            command_buffer.commit();
        }
    }

    fn render_frame(
        &mut self,
        scene: &Scene,
        texture: &metal::TextureRef,
        viewport_size: Size<DevicePixels>,
    ) -> Result<metal::CommandBuffer> {
        let mut writer = InstanceBufferWriter::new(
            &self.device,
            &self.instance_buffer_pool,
            self.is_unified_memory,
        );
        let instance_bindings = write_instances(scene, &mut writer).with_context(|| {
            format!(
                "scene too large: {} paths, {} shadows, {} quads, {} underlines, {} mono, {} poly, {} surfaces",
                scene.paths.len(),
                scene.shadows.len(),
                scene.quads.len(),
                scene.underlines.len(),
                scene.monochrome_sprites.len(),
                scene.polychrome_sprites.len(),
                scene.surfaces.len(),
            )
        })?;
        let command_buffer = self.draw_primitives_to_texture(
            scene,
            &instance_bindings,
            &mut writer,
            texture,
            viewport_size,
        )?;

        let instance_buffer_pool = self.instance_buffer_pool.clone();
        let instance_buffer = Cell::new(Some(writer.finish()));
        let block = ConcreteBlock::new(move |_| {
            if let Some(instance_buffer) = instance_buffer.take() {
                instance_buffer_pool.lock().release(instance_buffer);
            }
        });
        let block = block.copy();
        command_buffer.add_completed_handler(&block);

        Ok(command_buffer)
    }

    /// Renders the scene to a texture and returns the pixel data as an RGBA image.
    /// This does not present the frame to screen - useful for visual testing
    /// where we want to capture what would be rendered without displaying it.
    ///
    /// Note: This requires a layer-backed renderer. For headless rendering,
    /// use `render_scene_to_image()` instead.
    #[cfg(any(test, feature = "test-support"))]
    pub fn render_to_image(&mut self, scene: &Scene) -> Result<RgbaImage> {
        let layer = self
            .layer
            .clone()
            .ok_or_else(|| anyhow::anyhow!("render_to_image requires a layer-backed renderer"))?;
        let viewport_size = layer.drawable_size();
        let viewport_size: Size<DevicePixels> = size(
            (viewport_size.width.ceil() as i32).into(),
            (viewport_size.height.ceil() as i32).into(),
        );
        let drawable = layer
            .next_drawable()
            .ok_or_else(|| anyhow::anyhow!("Failed to get drawable for render_to_image"))?;

        let command_buffer = self.render_frame(scene, drawable.texture(), viewport_size)?;

        // Commit and wait for completion without presenting
        command_buffer.commit();
        command_buffer.wait_until_completed();

        read_texture_to_image(drawable.texture())
    }

    /// Renders a scene to an image without requiring a window or CAMetalLayer.
    ///
    /// This is the primary method for headless rendering. It creates an offscreen
    /// texture, renders the scene to it, and returns the pixel data as an RGBA image.
    #[cfg(any(test, feature = "bench-support", feature = "test-support"))]
    pub fn render_scene_to_image(
        &mut self,
        scene: &Scene,
        size: Size<DevicePixels>,
    ) -> Result<RgbaImage> {
        if size.width.0 <= 0 || size.height.0 <= 0 {
            anyhow::bail!("Invalid size for render_scene_to_image: {:?}", size);
        }

        // Update path intermediate textures for this size
        self.update_path_intermediate_textures(size);

        // Create an offscreen texture as render target
        let texture_descriptor = metal::TextureDescriptor::new();
        texture_descriptor.set_width(size.width.0 as u64);
        texture_descriptor.set_height(size.height.0 as u64);
        texture_descriptor.set_pixel_format(MTLPixelFormat::BGRA8Unorm);
        texture_descriptor
            .set_usage(metal::MTLTextureUsage::RenderTarget | metal::MTLTextureUsage::ShaderRead);
        texture_descriptor.set_storage_mode(metal::MTLStorageMode::Managed);
        let target_texture = self.device.new_texture(&texture_descriptor);

        let command_buffer = self.render_frame(scene, &target_texture, size)?;

        // On discrete GPUs (non-unified memory), Managed textures require an
        // explicit blit synchronize before the CPU can read back the rendered
        // data. Without this, get_bytes returns stale zeros.
        if !self.is_unified_memory {
            let blit = command_buffer.new_blit_command_encoder();
            blit.synchronize_resource(&target_texture);
            blit.end_encoding();
        }

        // Commit and wait for completion
        command_buffer.commit();
        command_buffer.wait_until_completed();

        read_texture_to_image(&target_texture)
    }

    /// Renders a scene to a reused offscreen texture without reading pixels
    /// back or blocking on GPU completion.
    ///
    /// This mirrors the CPU cost of presenting a frame to a window (scene
    /// encoding, instance buffer writes, command submission) and is used by
    /// headless benchmark rendering, where the produced pixels are never
    /// inspected.
    #[cfg(any(test, feature = "bench-support", feature = "test-support"))]
    pub fn render_scene(&mut self, scene: &Scene, size: Size<DevicePixels>) -> Result<()> {
        if size.width.0 <= 0 || size.height.0 <= 0 {
            anyhow::bail!("Invalid size for render_scene: {:?}", size);
        }

        self.update_path_intermediate_textures(size);

        let needs_new_target = self.headless_render_target.as_ref().is_none_or(|texture| {
            texture.width() != size.width.0 as u64 || texture.height() != size.height.0 as u64
        });
        if needs_new_target {
            let texture_descriptor = metal::TextureDescriptor::new();
            texture_descriptor.set_width(size.width.0 as u64);
            texture_descriptor.set_height(size.height.0 as u64);
            texture_descriptor.set_pixel_format(MTLPixelFormat::BGRA8Unorm);
            texture_descriptor.set_usage(
                metal::MTLTextureUsage::RenderTarget | metal::MTLTextureUsage::ShaderRead,
            );
            texture_descriptor.set_storage_mode(metal::MTLStorageMode::Private);
            self.headless_render_target = Some(self.device.new_texture(&texture_descriptor));
        }
        let target_texture = self
            .headless_render_target
            .clone()
            .expect("just ensured the render target exists");

        let command_buffer = self.render_frame(scene, &target_texture, size)?;

        // Commit without waiting, mirroring presentation to a real window where
        // the CPU doesn't block on the GPU.
        command_buffer.commit();
        Ok(())
    }

    fn draw_primitives_to_texture(
        &mut self,
        scene: &Scene,
        instance_bindings: &InstanceBindings,
        writer: &mut InstanceBufferWriter,
        texture: &metal::TextureRef,
        viewport_size: Size<DevicePixels>,
    ) -> Result<metal::CommandBuffer> {
        let command_queue = self.command_queue.clone();
        let command_buffer = command_queue.new_command_buffer();
        let alpha = if self.opaque { 1. } else { 0. };
        let filtered =
            filters_enabled() && (!scene.effects.is_empty() || !scene.backdrops.is_empty());
        let targets = filtered.then(|| self.filter_targets(viewport_size));
        // Backdrops read what the frame has drawn so far, which a drawable cannot be sampled from,
        // so a frame carrying them is drawn offscreen and blitted back at the end.
        let mirrored = !scene.backdrops.is_empty();
        let held = targets.as_ref();
        let main_texture: &metal::TextureRef = match (held, mirrored) {
            (Some(held), true) => &held.frame,
            _ => texture,
        };

        let mut command_encoder = new_command_encoder_for_texture(
            command_buffer,
            main_texture,
            viewport_size,
            Some(metal::MTLClearColor::new(0., 0., 0., alpha)),
        );

        let mut stack: Vec<usize> = Vec::new();
        // What each open layer will be composited through: neighbours that ask for the same filter
        // share one target, so a list of separately blurred rows costs one pass, not one per row.
        let mut spans: Vec<Bounds<ScaledPixels>> = Vec::new();
        let mut cleared = [false; LAYER_DEPTH];
        let mut transformed_target = [false; LAYER_DEPTH];

        for batch in scene.batches() {
            let wanted = held
                .and_then(|_| scene.filtered(scene.batch_order(&batch)))
                .map(|index| scene.filter_chain(index))
                .unwrap_or_default();
            let shared = stack
                .iter()
                .zip(wanted.iter())
                .take_while(|(open, next)| open == next)
                .count();

            let mut merged = false;
            while stack.len() > shared {
                if stack.len() == shared + 1
                    && wanted.len() == stack.len()
                    && let Some(open) = stack.last_mut()
                    && let Some(span) = spans.last_mut()
                {
                    let next = scene.effects[wanted[shared]];
                    let layer = scene.effects[*open];
                    if layer.can_merge_with(&next) {
                        *open = wanted[shared];
                        *span = span.union(&next.destination_clip());
                        merged = true;
                        break;
                    }
                }

                let index = stack.pop().expect("the stack is not empty");
                let held = held.expect("a filtered layer implies its targets");
                let layer = scene.effects[index];
                let clip = spans.pop().unwrap_or_else(|| layer.destination_clip());
                let source: &metal::TextureRef = &held.layers[stack.len().min(LAYER_DEPTH - 1)];
                let onto: &metal::TextureRef = match stack.last() {
                    Some(_) => &held.layers[(stack.len() - 1).min(LAYER_DEPTH - 1)],
                    None => main_texture,
                };

                command_encoder.end_encoding();
                let blurred = match layer.filter.blurs() {
                    true => self.blur_source(
                        held,
                        command_buffer,
                        source,
                        layer.filter.blur,
                        Some(layer.blur_bounds(clip)),
                        viewport_size,
                    ),
                    false => source,
                };
                self.composite_layer(command_buffer, blurred, onto, layer, clip, viewport_size);
                command_encoder =
                    new_command_encoder_for_texture(command_buffer, onto, viewport_size, None);
            }

            for index in wanted.iter().skip(shared + usize::from(merged)) {
                if stack.len() >= LAYER_DEPTH {
                    break;
                }
                let held = held.expect("a filtered layer implies its targets");
                let layer = scene.effects[*index];
                let depth = stack.len();
                let should_clear =
                    !cleared[depth] || layer.filter.transforms() || transformed_target[depth];
                let clear = match should_clear {
                    true => Some(metal::MTLClearColor::new(0., 0., 0., 0.)),
                    false => None,
                };
                cleared[depth] = true;
                transformed_target[depth] = layer.filter.transforms();

                command_encoder.end_encoding();
                command_encoder = new_command_encoder_for_texture(
                    command_buffer,
                    &held.layers[depth],
                    viewport_size,
                    clear,
                );
                stack.push(*index);
                spans.push(layer.destination_clip());
            }

            match batch {
                PrimitiveBatch::Shadows(range) => {
                    self.draw_shadows(range, instance_bindings, viewport_size, command_encoder)
                }
                PrimitiveBatch::Quads(range) => {
                    self.draw_quads(range, instance_bindings, viewport_size, command_encoder)
                }
                PrimitiveBatch::Paths(range) => {
                    let paths = &scene.paths[range];
                    let onto = open_target(&stack, held, main_texture);
                    command_encoder.end_encoding();

                    let did_draw = self.draw_paths_to_intermediate(
                        paths,
                        writer,
                        viewport_size,
                        command_buffer,
                    )?;

                    command_encoder =
                        new_command_encoder_for_texture(command_buffer, onto, viewport_size, None);

                    if did_draw {
                        if let Err(error) = self.draw_paths_from_intermediate(
                            paths,
                            writer,
                            viewport_size,
                            command_encoder,
                        ) {
                            command_encoder.end_encoding();
                            return Err(error);
                        }
                    }
                }
                PrimitiveBatch::Underlines(range) => {
                    self.draw_underlines(range, instance_bindings, viewport_size, command_encoder)
                }
                PrimitiveBatch::MonochromeSprites { texture_id, range } => self
                    .draw_monochrome_sprites(
                        texture_id,
                        range,
                        instance_bindings,
                        viewport_size,
                        command_encoder,
                    ),
                PrimitiveBatch::PolychromeSprites { texture_id, range } => self
                    .draw_polychrome_sprites(
                        texture_id,
                        range,
                        instance_bindings,
                        viewport_size,
                        command_encoder,
                    ),
                PrimitiveBatch::Backdrops(range) => {
                    let Some(held) = held.filter(|_| stack.is_empty()) else {
                        continue;
                    };
                    let backdrops = &scene.backdrops[range.clone()];
                    let sigma = backdrops
                        .iter()
                        .fold(0., |widest: f32, backdrop| widest.max(backdrop.blur));
                    // A backdrop samples the blur only within its own bounds, so the passes
                    // are scissored to the union of the batch's, grown by the kernel inside
                    // `blur_source`, rather than run over the whole frame.
                    let clip = backdrops
                        .iter()
                        .map(|backdrop| backdrop.bounds)
                        .reduce(|union, bounds| union.union(&bounds));

                    command_encoder.end_encoding();
                    let blurred = self.blur_source(
                        held,
                        command_buffer,
                        &held.frame,
                        sigma,
                        clip,
                        viewport_size,
                    );
                    command_encoder = new_command_encoder_for_texture(
                        command_buffer,
                        main_texture,
                        viewport_size,
                        None,
                    );
                    self.draw_backdrops(
                        range,
                        instance_bindings,
                        blurred,
                        viewport_size,
                        command_encoder,
                    );
                }
                PrimitiveBatch::Surfaces(range) => self.draw_surfaces(
                    &scene.surfaces[range.clone()],
                    range.start,
                    instance_bindings,
                    viewport_size,
                    command_encoder,
                ),
                PrimitiveBatch::SubpixelSprites { .. } => unreachable!(),
            }
        }

        while let Some(index) = stack.pop() {
            let held = held.expect("a filtered layer implies its targets");
            let layer = scene.effects[index];
            let clip = spans.pop().unwrap_or_else(|| layer.destination_clip());
            let source: &metal::TextureRef = &held.layers[stack.len().min(LAYER_DEPTH - 1)];
            let onto: &metal::TextureRef = match stack.last() {
                Some(_) => &held.layers[(stack.len() - 1).min(LAYER_DEPTH - 1)],
                None => main_texture,
            };

            command_encoder.end_encoding();
            let blurred = match layer.filter.blurs() {
                true => self.blur_source(
                    held,
                    command_buffer,
                    source,
                    layer.filter.blur,
                    Some(layer.blur_bounds(clip)),
                    viewport_size,
                ),
                false => source,
            };
            self.composite_layer(command_buffer, blurred, onto, layer, clip, viewport_size);
            command_encoder =
                new_command_encoder_for_texture(command_buffer, onto, viewport_size, None);
        }

        command_encoder.end_encoding();

        if let Some(held) = held.filter(|_| mirrored) {
            self.filter_pass(
                command_buffer,
                &self.blit_pipeline_state,
                &held.frame,
                texture,
                None,
                None,
            );
        }

        Ok(command_buffer.to_owned())
    }

    /// The targets the frame blurs and masks through, rebuilt whenever the viewport changes.
    fn filter_targets(&mut self, viewport_size: Size<DevicePixels>) -> FilterTargets {
        let stale = self
            .filter_targets
            .as_ref()
            .is_none_or(|targets| targets.size != viewport_size);
        if stale {
            let width = i32::from(viewport_size.width).max(1) as u64;
            let height = i32::from(viewport_size.height).max(1) as u64;
            let target = |width: u64, height: u64| {
                let descriptor = metal::TextureDescriptor::new();
                descriptor.set_texture_type(metal::MTLTextureType::D2);
                descriptor.set_pixel_format(MTLPixelFormat::BGRA8Unorm);
                descriptor.set_width(width.max(1));
                descriptor.set_height(height.max(1));
                descriptor.set_storage_mode(metal::MTLStorageMode::Private);
                descriptor.set_usage(
                    metal::MTLTextureUsage::RenderTarget | metal::MTLTextureUsage::ShaderRead,
                );
                self.device.new_texture(&descriptor)
            };

            self.filter_targets = Some(FilterTargets {
                size: viewport_size,
                frame: target(width, height),
                layers: (0..LAYER_DEPTH).map(|_| target(width, height)).collect(),
                steps: BLUR_STEPS
                    .iter()
                    .map(|shrink| {
                        let shrink = *shrink as u64;
                        [
                            target(width / shrink, height / shrink),
                            target(width / shrink, height / shrink),
                        ]
                    })
                    .collect(),
            });
        }

        self.filter_targets
            .clone()
            .expect("the targets were just built")
    }

    /// Clamps a region to the target it is drawn into, shrunk to the blur step it runs at.
    fn scissor(
        bounds: Bounds<ScaledPixels>,
        viewport_size: Size<DevicePixels>,
        shrink: u32,
    ) -> Option<metal::MTLScissorRect> {
        let shrink = shrink as f32;
        let width = (i32::from(viewport_size.width) as f32 / shrink).floor();
        let height = (i32::from(viewport_size.height) as f32 / shrink).floor();
        let left = (bounds.origin.x.0 / shrink).floor().clamp(0., width);
        let top = (bounds.origin.y.0 / shrink).floor().clamp(0., height);
        let right = ((bounds.origin.x.0 + bounds.size.width.0) / shrink)
            .ceil()
            .clamp(left, width);
        let bottom = ((bounds.origin.y.0 + bounds.size.height.0) / shrink)
            .ceil()
            .clamp(top, height);
        if right <= left || bottom <= top {
            return None;
        }

        Some(metal::MTLScissorRect {
            x: left as u64,
            y: top as u64,
            width: (right - left) as u64,
            height: (bottom - top) as u64,
        })
    }

    /// Draws one full-screen pass of a filter from `source` into `target`.
    fn filter_pass(
        &self,
        command_buffer: &metal::CommandBufferRef,
        pipeline: &metal::RenderPipelineState,
        source: &metal::TextureRef,
        target: &metal::TextureRef,
        params: Option<&BlurParams>,
        within: Option<metal::MTLScissorRect>,
    ) {
        let size = size(
            DevicePixels(target.width() as i32),
            DevicePixels(target.height() as i32),
        );
        let encoder = new_command_encoder_for_texture(
            command_buffer,
            target,
            size,
            Some(metal::MTLClearColor::new(0., 0., 0., 0.)),
        );
        encoder.set_render_pipeline_state(pipeline);
        encoder.set_fragment_texture(FilterInputIndex::Source as u64, Some(source));
        if let Some(params) = params {
            encoder.set_fragment_bytes(
                FilterInputIndex::Params as u64,
                mem::size_of::<BlurParams>() as u64,
                params as *const BlurParams as *const _,
            );
        }
        if let Some(within) = within {
            encoder.set_scissor_rect(within);
        }
        encoder.draw_primitives(metal::MTLPrimitiveType::TriangleStrip, 0, 4);
        encoder.end_encoding();
    }

    /// Blurs a source into one of the ping-pong targets and returns the one holding the result.
    ///
    /// The resolution follows the radius: a small blur stays at full resolution, where downsampling
    /// would turn text into mush, and only a wide one is worth shrinking first.
    fn blur_source<'a>(
        &self,
        targets: &'a FilterTargets,
        command_buffer: &metal::CommandBufferRef,
        source: &'a metal::TextureRef,
        sigma: f32,
        clip: Option<Bounds<ScaledPixels>>,
        viewport_size: Size<DevicePixels>,
    ) -> &'a metal::TextureRef {
        let step = BLUR_STEPS
            .iter()
            .position(|shrink| sigma <= BLUR_REACH * *shrink as f32)
            .unwrap_or(BLUR_STEPS.len() - 1);
        let shrink = BLUR_STEPS[step] as f32;
        let across = BlurParams {
            direction_x: 1.,
            direction_y: 0.,
            sigma: sigma / shrink,
            pad: 0.,
        };
        let down = BlurParams {
            direction_x: 0.,
            direction_y: 1.,
            sigma: sigma / shrink,
            pad: 0.,
        };
        // Each pass reads a kernel's width beyond what the next one needs, so the region grows
        // from the composited clip outwards.
        let within = |margin: f32, shrink: u32| {
            clip.and_then(|clip| {
                Self::scissor(clip.dilate(ScaledPixels(margin)), viewport_size, shrink)
            })
        };

        let mut from = source;
        for shrunk in 0..step {
            let shrink = BLUR_STEPS[shrunk + 1];
            self.filter_pass(
                command_buffer,
                &self.blit_pipeline_state,
                from,
                &targets.steps[shrunk + 1][0],
                None,
                within(sigma * BLUR_REACH * 2., shrink),
            );
            from = &targets.steps[shrunk + 1][0];
        }

        let shrink = BLUR_STEPS[step];
        let [held, scratch] = &targets.steps[step];
        self.filter_pass(
            command_buffer,
            &self.blur_pipeline_state,
            from,
            scratch,
            Some(&across),
            within(sigma * BLUR_REACH, shrink),
        );
        self.filter_pass(
            command_buffer,
            &self.blur_pipeline_state,
            scratch,
            held,
            Some(&down),
            within(0., shrink),
        );

        held
    }

    /// Draws a filtered layer back into its parent, clipped to the layer's bounds.
    fn composite_layer(
        &self,
        command_buffer: &metal::CommandBufferRef,
        source: &metal::TextureRef,
        onto: &metal::TextureRef,
        layer: LayerEffect,
        clip: Bounds<ScaledPixels>,
        viewport_size: Size<DevicePixels>,
    ) {
        let Some(within) = Self::scissor(layer.destination_scissor_bounds(clip), viewport_size, 1)
        else {
            return;
        };
        let masked = layer.filter.fades();
        let encoder = new_command_encoder_for_texture(command_buffer, onto, viewport_size, None);
        encoder.set_render_pipeline_state(match masked {
            true => &self.masked_pipeline_state,
            false => &self.composite_pipeline_state,
        });
        encoder.set_fragment_texture(FilterInputIndex::Source as u64, Some(source));
        encoder.set_fragment_bytes(
            FilterInputIndex::ViewportSize as u64,
            mem::size_of_val(&viewport_size) as u64,
            &viewport_size as *const Size<DevicePixels> as *const _,
        );
        let params = mask_params(layer, clip);
        encoder.set_fragment_bytes(
            FilterInputIndex::Params as u64,
            mem::size_of::<MaskParams>() as u64,
            &params as *const MaskParams as *const _,
        );
        encoder.set_scissor_rect(within);
        encoder.draw_primitives(metal::MTLPrimitiveType::TriangleStrip, 0, 4);
        encoder.end_encoding();
    }

    fn draw_backdrops(
        &self,
        backdrops: Range<usize>,
        instance_bindings: &InstanceBindings,
        source: &metal::TextureRef,
        viewport_size: Size<DevicePixels>,
        command_encoder: &metal::RenderCommandEncoderRef,
    ) {
        if backdrops.is_empty() {
            return;
        }

        command_encoder.set_render_pipeline_state(&self.backdrops_pipeline_state);
        command_encoder.set_vertex_buffer(
            FilterInputIndex::Vertices as u64,
            Some(&self.unit_vertices),
            0,
        );
        command_encoder.set_vertex_buffer(
            FilterInputIndex::Backdrops as u64,
            Some(&instance_bindings.backdrops.buffer),
            instance_bindings.backdrops.offset as u64,
        );
        command_encoder.set_fragment_buffer(
            FilterInputIndex::Backdrops as u64,
            Some(&instance_bindings.backdrops.buffer),
            instance_bindings.backdrops.offset as u64,
        );
        command_encoder.set_vertex_bytes(
            FilterInputIndex::ViewportSize as u64,
            mem::size_of_val(&viewport_size) as u64,
            &viewport_size as *const Size<DevicePixels> as *const _,
        );
        command_encoder.set_fragment_bytes(
            FilterInputIndex::ViewportSize as u64,
            mem::size_of_val(&viewport_size) as u64,
            &viewport_size as *const Size<DevicePixels> as *const _,
        );
        command_encoder.set_fragment_texture(FilterInputIndex::Source as u64, Some(source));
        command_encoder.draw_primitives_instanced(
            metal::MTLPrimitiveType::Triangle,
            0,
            6,
            backdrops.len() as u64,
        );
    }

    fn draw_paths_to_intermediate(
        &self,
        paths: &[Path<ScaledPixels>],
        writer: &mut InstanceBufferWriter,
        viewport_size: Size<DevicePixels>,
        command_buffer: &metal::CommandBufferRef,
    ) -> Result<bool> {
        if paths.is_empty() {
            return Ok(false);
        }
        let intermediate_texture = self
            .path_intermediate_texture
            .as_ref()
            .context("missing path intermediate texture")?;

        let mut vertices = Vec::new();
        for path in paths {
            vertices.extend(path.vertices.iter().map(|v| PathRasterizationVertex {
                xy_position: v.xy_position,
                st_position: v.st_position,
                color: path.color,
                bounds: path.bounds.intersect(&path.content_mask.bounds),
            }));
        }
        let vertex_instance_bindings = writer.write(&vertices)?;

        let render_pass_descriptor = metal::RenderPassDescriptor::new();
        let color_attachment = render_pass_descriptor
            .color_attachments()
            .object_at(0)
            .unwrap();
        color_attachment.set_load_action(metal::MTLLoadAction::Clear);
        color_attachment.set_clear_color(metal::MTLClearColor::new(0., 0., 0., 0.));

        if let Some(msaa_texture) = &self.path_intermediate_msaa_texture {
            color_attachment.set_texture(Some(msaa_texture));
            color_attachment.set_resolve_texture(Some(intermediate_texture));
            color_attachment.set_store_action(metal::MTLStoreAction::MultisampleResolve);
        } else {
            color_attachment.set_texture(Some(intermediate_texture));
            color_attachment.set_store_action(metal::MTLStoreAction::Store);
        }

        let command_encoder = command_buffer.new_render_command_encoder(render_pass_descriptor);
        command_encoder.set_render_pipeline_state(&self.paths_rasterization_pipeline_state);
        command_encoder.set_vertex_buffer(
            PathRasterizationInputIndex::Vertices as u64,
            Some(&vertex_instance_bindings.buffer),
            vertex_instance_bindings.offset as u64,
        );
        command_encoder.set_vertex_bytes(
            PathRasterizationInputIndex::ViewportSize as u64,
            mem::size_of_val(&viewport_size) as u64,
            &viewport_size as *const Size<DevicePixels> as *const _,
        );
        command_encoder.set_fragment_buffer(
            PathRasterizationInputIndex::Vertices as u64,
            Some(&vertex_instance_bindings.buffer),
            vertex_instance_bindings.offset as u64,
        );
        command_encoder.draw_primitives(
            metal::MTLPrimitiveType::Triangle,
            0,
            vertices.len() as u64,
        );

        command_encoder.end_encoding();
        Ok(true)
    }

